# функция одной переменной (лабы 2-3)
def f1(x):
    return x**2 + 4*x + 6

A0, B0 = -4, 6  # начальная точка (отрезок [a0; b0]) для f1



# функция двух переменных (лаба 4): a*x1^2 + b*x2^2 + c*x1*x2 + d*x1 + e*x2 + f
A, B, C, D, E, F = 7, 1, -1, 1, 0, 0
X0 = (1, 2)  # начальная точка для f2

def f2(x1, x2):
    return A*x1**2 + B*x2**2 + C*x1*x2 + D*x1 + E*x2 + F

def grad_f2(x1, x2):
    # частные производные: f_x1'(x) = 2a*x1 + c*x2 + d, f_x2'(x) = 2b*x2 + c*x1 + e
    return [2*A*x1 + C*x2 + D, 2*B*x2 + C*x1 + E]

# точка минимума f2: решение системы grad f2 = 0
# 2a*x1 + c*x2 = -d,
# c*x1 + 2b*x2 = -e
# проверки, является ли подозрительная точка минимумом, НЕТ
_DET = 4*A*B - C**2
X_MIN = ((-2*B*D + E*C) / _DET, (-2*A*E + C*D) / _DET)  # для текущих коэффициентов (-2/27; -1/27)

def hess_f2(x1, x2):
    # матрица Гессе (вторые производные): f_x1x1 = 2a, f_x1x2 = f_x2x1 = c, f_x2x2 = 2b
    return [[2*A, C],
            [C, 2*B]]

# ограничение для лабораторных работ 5-6: u*x1 + v*x2 - w = 0
U, V, W = 1, 1, 2

def g1(x1, x2):
    return U*x1 + V*x2 - W

def grad_g1(x1, x2):
    return [U, V]

def hess_g1(x1, x2):
    return [[0, 0],
            [0, 0]]

if V != 0:
    # точка условного минимума f2 при линейном ограничении g1 = 0
    # выражаем x2 из ограничения: Ux1+Vx2=W => x2 = (W-Ux1)/V = a + b*x1
    a = W / V
    b = -U / V

    # коэффициенты при x1^2 и x1 после подстановки в целевую функцию:
    # f(x1,x2) = A*x1^2 + B*x2^2 + C*x1*x2 + D*x1 + E*x2 + F; подставим сюда x2 выраженный через x1
    # f(x1) = (A+Bb**2+Cb)x1**2 + (2Bab+Ca+D+Eb)x1 + (Ba**2+Ea+F)
    # это парабола при alpha != 0 - пересечение параболоида f(x1,x2) и плоскости g1(x1,x2)=0
    alpha = A + B * b ** 2 + C * b
    if alpha <= 0:
        raise ValueError("Нет единственного условного минимума")
    beta = 2 * B * a * b + C * a + D + E * b

    # находим условный минимум - вершину получившейся параболы
    x1_min = -beta / (2 * alpha)
    x2_min = a + b * x1_min

elif U != 0:
    # Ux1=W =>
    x1_min = W / U
    # после подстановки x1 в f(x1,x2):
    # f(x2) = Bx2**2 + (CW/U+E)x2 + (AW**2/U**2+DW/U+F) - парабола: пересечение параболоида и плоскости
    if B <= 0:
        raise ValueError("Нет единственного условного минимума")
    x2_min = -(C * x1_min + E)/(2 * B)

else:
    raise ValueError("U и V не должны равняться нулю одновременно: неверно задано ограничение-равенство")

X_MIN_CONSTRAINED = (x1_min, x2_min)